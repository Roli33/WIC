-- | Calculates the byte size of a given type.
sizeOf :: Layout -> Type -> Int
sizeOf l ty = case ty of
    Int -> 1; Double -> 1; Bool -> 1; Char -> 1; Void -> 1; Ptr _ -> 1; Enum _ -> 1
    ConstT t -> sizeOf l t
    Array t (Just (Expr _ (IntLit n))) -> fromIntegral n * sizeOf l t
    Array t _ -> sizeOf l t
    Struct n -> case M.lookup n (lStructs l) of
        Just fields -> sum (map (\(t,_) -> sizeOf l t) fields)
        Nothing -> 1
    Union n -> case M.lookup n (lUnions l) of
        Just fields -> if null fields then 1 else maximum (map (\(t,_) -> sizeOf l t) fields)
        Nothing -> 1

-- | Calculates the memory offset of a specific property within a struct/union.
offsetOf :: Layout -> Type -> String -> Maybe Int
offsetOf l ty prop = case ty of
    Struct n -> do
        fields <- M.lookup n (lStructs l)
        let go [] = Nothing
            go ((t, name):fs)
                | name == prop = Just 0
                | otherwise    = (+ sizeOf l t) <$> go fs
        go fields
    Union _ -> Just 0 
    ConstT t -> offsetOf l t prop
    _ -> Nothing

-- | Retrieves the type of a specific field within a struct or union.
fieldType :: Layout -> Type -> String -> Maybe Type
fieldType l ty prop = case ty of
    Struct n -> M.lookup n (lStructs l) >>= lookup prop . map (\(t,nm) -> (nm,t))
    Union n  -> M.lookup n (lUnions l)  >>= lookup prop . map (\(t,nm) -> (nm,t))
    ConstT t -> fieldType l t prop
    _ -> Nothing

-- | Infers the type of an expression based on the current layout.
typeOf :: Layout -> Expr -> Maybe Type
typeOf l (Expr _ node) = case node of
    Var x        -> M.lookup x (lEnv l) >>= \addr -> M.lookup addr (lTypes l)
    Field e prop -> typeOf l e >>= \ty -> fieldType l ty prop
    Index e _    -> typeOf l e >>= \ty -> case ty of
        Array t _ -> Just t
        Ptr t     -> Just t
        _         -> Nothing
    Deref e      -> typeOf l e >>= \ty -> case ty of
        Ptr t     -> Just t
        Array t _ -> Just t
        _         -> Nothing
    AddrOf e     -> typeOf l e >>= \ty -> Just (Ptr ty)
    _            -> Nothing

-- | Evaluates an expression to find its corresponding memory address (l-value).
lvalue :: Layout -> Heap -> Expr -> Maybe Addr
lvalue l heap (Expr _ node) = case node of
    Var x        -> M.lookup x (lEnv l)
    Field e prop -> do
        baseAddr <- lvalue l heap e
        baseTy   <- typeOf l e
        off      <- offsetOf l baseTy prop
        return (baseAddr + off)
    Index e idx  -> do
        baseAddr <- lvalue l heap e
        baseTy   <- typeOf l e
        let elemSz = case baseTy of
                Array t _ -> sizeOf l t
                Ptr t     -> sizeOf l t
                _         -> 1
        idxVal <- case evalPure l heap idx of
            VInt i -> Just (fromIntegral i)
            _      -> Nothing
        return (baseAddr + idxVal * elemSz)
    Deref e      -> case evalPure l heap e of
        VAddr addr -> Just addr
        _          -> Nothing
    _ -> Nothing

findBaseVars :: Layout -> Addr -> [(String, Addr, Type)]
findBaseVars l target =
    [ (name, baseAddr, ty)
    | (name, baseAddr) <- M.toList (lEnv l)
    , Just ty <- [M.lookup baseAddr (lTypes l)]
    , target >= baseAddr && target < baseAddr + sizeOf l ty
    ]

buildExpr :: Layout -> Type -> Addr -> Addr -> Expr -> Maybe Expr
buildExpr l ty baseAddr targetAddr currentExpr
    | baseAddr == targetAddr = Just currentExpr
    | otherwise = case ty of
        Struct n -> do
            fields <- M.lookup n (lStructs l)
            let findField [] _ = Nothing
                findField ((ft, fname):fs) currentOff
                    | targetAddr >= baseAddr + currentOff && targetAddr < baseAddr + currentOff + sizeOf l ft =
                        buildExpr l ft (baseAddr + currentOff) targetAddr (genExpr (Field currentExpr fname))
                    | otherwise = findField fs (currentOff + sizeOf l ft)
            findField fields 0
        Union n -> do
            fields <- M.lookup n (lUnions l)
            case fields of
                ((ft, fname):_) -> buildExpr l ft baseAddr targetAddr (genExpr (Field currentExpr fname))
                _               -> Nothing
        Array t _ -> do
            let elemSz = sizeOf l t
            if elemSz == 0 then Nothing else do
                let idx = (targetAddr - baseAddr) `div` elemSz
                buildExpr l t (baseAddr + idx * elemSz) targetAddr (genExpr (Index currentExpr (genExpr (IntLit (fromIntegral idx)))))
        ConstT t -> buildExpr l t baseAddr targetAddr currentExpr
        _        -> Nothing

reverseLval :: Layout -> Addr -> [Expr]
reverseLval l target = do
    (name, baseAddr, ty) <- findBaseVars l target
    case buildExpr l ty baseAddr target (genExpr (Var name)) of
        Just expr -> [expr]
        Nothing   -> []


