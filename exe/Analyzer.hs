prettyTop :: Expr -> String
prettyTop expr@(Expr _ node) = case node of
    BinOp op e1 e2 -> prettyExpr e1 ++ " " ++ op ++ " " ++ prettyExpr e2
    Ternary c t e  -> prettyTop c ++ " ? " ++ prettyTop t ++ " : " ++ prettyTop e
    _              -> prettyExpr expr

prettyExpr :: Expr -> String
prettyExpr (Expr _ node) = case node of
    Var x         -> x
    IntLit n      -> show n
    DoubleLit d   -> show d
    BoolLit True  -> "true"
    BoolLit False -> "false"
    CharLit c     -> show c
    StringLit s   -> show s
    Index e1 e2   -> prettyExpr e1 ++ "[" ++ prettyTop e2 ++ "]"
    Call f args   -> f ++ "(" ++ intercalate ", " (map prettyTop args) ++ ")"
    Field e p     -> prettyExpr e ++ "." ++ p
    Deref e       -> "*" ++ prettyExpr e
    AddrOf e      -> "&" ++ prettyExpr e
    UnOp op e     -> op ++ prettyExpr e
    PreInc e      -> "++" ++ prettyExpr e
    PreDec e      -> "--" ++ prettyExpr e
    PostInc e     -> prettyExpr e ++ "++"
    PostDec e     -> prettyExpr e ++ "--"
    Ternary c t e -> "(" ++ prettyTop c ++ " ? " ++ prettyTop t ++ " : " ++ prettyTop e ++ ")"
    BinOp op e1 e2-> "(" ++ prettyExpr e1 ++ " " ++ op ++ " " ++ prettyExpr e2 ++ ")"


