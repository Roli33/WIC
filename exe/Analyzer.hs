type Addr = Int

-- | Represents values held in memory during concrete/hybrid execution.
data Value 
    = VInt Integer 
    | VDouble Double     
    | VChar Char         
    | VBool Bool 
    | VArray [Value]     
    | VAddr Addr         
    | VUnknown
    deriving (Show, Eq)

-- | The environment maps variable names to their memory addresses.
type SymEnv = M.Map String Addr      

-- | The heap maps memory addresses to concrete or symbolic values.
type Heap   = M.Map Addr Value       

-- | The symbolic store maps addresses to symbolic expressions for SMT solving.
type SymStore = M.Map Addr Expr      

-- | A pre-computed summary of a function's behavior.
data FuncSummary = FuncSummary
    { modifiedParams :: [String] -- ^ Which parameter names are mutated (pointers/arrays)
    , implicitPosts  :: [Expr]   -- ^ Derived logical facts about the return value ('res')
    } deriving (Show, Eq)

-- Add this to AnalyzerState:
-- 

data AnalyzerState = AnalyzerState
    { env        :: SymEnv                        -- ^ Current variable scope mapping
    , heap       :: Heap                          -- ^ Current state of memory
    , heapTypes  :: M.Map Addr Type               -- ^ Type metadata for memory addresses
    , structs    :: M.Map String [(Type, String)] -- ^ Struct definitions
    , unions     :: M.Map String [(Type, String)] -- ^ Union definitions
    , nextAddr   :: Addr                          -- ^ Pointer for the next memory allocation
    , facts      :: [Expr]                        -- ^ Accumulated logical facts (Path Conditions)
    , funcs      :: M.Map String Function         -- ^ Global function definitions
    , violations :: [(SourcePos, String, Expr)]   -- ^ Collected contract/safety failures
    , returnVal  :: Maybe Value                   -- ^ Holds the return value during block evaluation
    , summaries  :: M.Map String FuncSummary
    } deriving (Show)

-- | The primary Monad stack for the Analyzer: State over IO (required by Z3).
type Analyzer a = StateT AnalyzerState IO a
  
type FuncEnv   = M.Map String Function
type StructEnv = M.Map String [(Type, String)]
type UnionEnv  = M.Map String [(Type, String)]
type HeapTypes = M.Map Addr Type

-- | A snapshot of the memory layout rules and types.
data Layout = Layout
    { lStructs :: StructEnv
    , lUnions  :: UnionEnv
    , lTypes   :: HeapTypes
    , lEnv     :: SymEnv
    }

getLayout :: Analyzer Layout
getLayout = do
    s <- get
    return $ Layout (structs s) (unions s) (heapTypes s) (env s)


