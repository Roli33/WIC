z3SortForType :: Layout -> Maybe Type -> Z3 Z3.Sort
z3SortForType _ ty = case ty of
    Just Bool   -> mkBoolSort
    Just Double -> mkRealSort
    Just (Array _ _) -> do
        iSort <- mkIntSort
        vSort <- mkIntSort
        mkArraySort iSort vSort
    _ -> mkIntSort 

translateZ3 :: Layout -> FuncEnv -> Expr -> Z3 Z3.AST
translateZ3 l funcs (Expr _ node) = case node of
    IntLit n  -> mkIntNum n
    BoolLit b -> mkBool b
    DoubleLit d -> mkRealSort >>= mkNumeral (show d)
    Var x -> do
        sym <- mkStringSymbol x
        sorted <- z3SortForType l (typeOf l (genExpr node))
        mkVar sym sorted
    BinOp "+" e1 e2  -> do { a <- translateZ3 l funcs e1; b <- translateZ3 l funcs e2; mkAdd [a, b] }
    BinOp "-" e1 e2  -> do { a <- translateZ3 l funcs e1; b <- translateZ3 l funcs e2; mkSub [a, b] }
    BinOp "*" e1 e2  -> do { a <- translateZ3 l funcs e1; b <- translateZ3 l funcs e2; mkMul [a, b] }
    BinOp "/" e1 e2  -> do { a <- translateZ3 l funcs e1; b <- translateZ3 l funcs e2; mkDiv a b }
    BinOp "==" e1 e2 -> do { a <- translateZ3 l funcs e1; b <- translateZ3 l funcs e2; mkEq a b }
    BinOp "!=" e1 e2 -> do { a <- translateZ3 l funcs e1; b <- translateZ3 l funcs e2; eq <- mkEq a b; mkNot eq }
    BinOp "<" e1 e2  -> do { a <- translateZ3 l funcs e1; b <- translateZ3 l funcs e2; mkLt a b }
    BinOp "<=" e1 e2 -> do { a <- translateZ3 l funcs e1; b <- translateZ3 l funcs e2; mkLe a b }
    BinOp ">" e1 e2  -> do { a <- translateZ3 l funcs e1; b <- translateZ3 l funcs e2; mkGt a b }
    BinOp ">=" e1 e2 -> do { a <- translateZ3 l funcs e1; b <- translateZ3 l funcs e2; mkGe a b }
    BinOp "&&" e1 e2 -> do { a <- translateZ3 l funcs e1; b <- translateZ3 l funcs e2; mkAnd [a, b] }
    BinOp "||" e1 e2 -> do { a <- translateZ3 l funcs e1; b <- translateZ3 l funcs e2; mkOr [a, b] }
    UnOp "!" e       -> translateZ3 l funcs e >>= mkNot
    UnOp "-" e       -> translateZ3 l funcs e >>= mkUnaryMinus
    Ternary c t e -> do
        zC <- translateZ3 l funcs c
        zT <- translateZ3 l funcs t
        zE <- translateZ3 l funcs e
        mkIte zC zT zE

    Index arr idx -> do
        z3Arr <- translateZ3 l funcs arr
        z3Idx <- translateZ3 l funcs idx
        mkSelect z3Arr z3Idx

    ArrayUpdate arr idx val -> do
        z3Arr <- translateZ3 l funcs arr
        z3Idx <- translateZ3 l funcs idx
        z3Val <- translateZ3 l funcs val
        mkStore z3Arr z3Idx z3Val

    Call fname args -> do
        sym <- mkStringSymbol fname
        let retType = case M.lookup fname funcs of Just f -> Just (funcRetType f); Nothing -> Just Int
        
        retSort  <- z3SortForType l retType
        argSorts <- mapM (\arg -> z3SortForType l (typeOf l arg)) args
        funcDecl <- mkFuncDecl sym argSorts retSort
        
        if null args 
            then mkApp funcDecl []
            else do
                z3Args <- mapM (translateZ3 l funcs) args
                mkApp funcDecl z3Args

    _ -> mkStringSymbol (show node) >>= mkIntVar 

-- | Proves if a given condition logically follows from a set of known facts using Z3.
proveZ3 :: Layout -> FuncEnv -> [Expr] -> Expr -> IO Value
proveZ3 l funcs facts condition = evalZ3 $ do
    z3Facts <- mapM (translateZ3 l funcs) facts
    z3Cond  <- translateZ3 l funcs condition
    mapM_ assert z3Facts
    
    -- We prove the condition by asserting its negation and looking for a contradiction (Unsat)
    notCond <- mkNot z3Cond
    assert notCond
    res <- check
    case res of
        Unsat -> return (VBool True)  -- Negation is impossible; condition is proven TRUE
        Sat   -> return (VBool False) -- Found a model where condition is false
        Undef -> return VUnknown      -- SMT solver timed out or gave up


