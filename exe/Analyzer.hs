-- | Evaluates an expression, checking preconditions if a function call is encountered.
evalExpr :: Expr -> Analyzer Value
evalExpr e@(Expr callPos node) = do
    l         <- getLayout
    currHeap  <- gets heap
    currFacts <- gets facts
    currFuncs <- gets funcs

    case node of
        Call fname argExprs -> do
            case M.lookup fname currFuncs of
                Nothing -> return VUnknown
                Just funcDef -> do
                    let paramNames = map (\(Arg _ n) -> n) (funcArgs funcDef)
                    let subs = zip (map (genExpr . Var) paramNames) argExprs
                    case funcInvars funcDef of
                        Nothing     -> return ()
                        Just invars -> forM_ (concatMap splitAnds invars) $ \inv -> do
                            let callerScopeInv = substituteMany subs inv
                            let evalInv        = partialEval l currHeap callerScopeInv
                            let evalFacts      = map (partialEval l currHeap) currFacts
                            
                            isProven <- liftIO $ proveZ3 l currFuncs evalFacts evalInv
                            when (isProven == VBool False || isProven == VUnknown) $ 
                                modify (\s -> s { violations = ((callPos, "Precondition Failed in: " ++ fname, callerScopeInv) : violations s) })
                    return VUnknown
        BinOp op e1 e2 -> applyOp op <$> evalExpr e1 <*> evalExpr e2
        UnOp op ex     -> applyUnOp op <$> evalExpr ex
        Ternary c t ex -> do
            condVal <- evalExpr c
            case condVal of 
                VBool True  -> evalExpr t
                VBool False -> evalExpr ex
                _           -> return VUnknown
        _ -> return $ evalPure l currHeap e

-- | Symbolically evaluates an expression against a symbolic store.
symEval :: Layout -> Heap -> SymStore -> Expr -> Expr
symEval l heap store expr@(Expr pos node) = case node of
    Var _                   -> checkStore expr
    Field _ _               -> checkStore expr
    Deref _                 -> checkStore expr
    Index arr idx           -> Expr pos (Index (symEval l heap store arr) (symEval l heap store idx))
    ArrayUpdate arr idx val -> Expr pos (ArrayUpdate (symEval l heap store arr) (symEval l heap store idx) (symEval l heap store val))
    BinOp op e1 e2          -> Expr pos (BinOp op (symEval l heap store e1) (symEval l heap store e2))
    UnOp op e               -> Expr pos (UnOp op (symEval l heap store e))
    Call fname args         -> Expr pos (Call fname (map (symEval l heap store) args))
    Ternary c t e           -> Expr pos (Ternary (symEval l heap store c) (symEval l heap store t) (symEval l heap store e))
    _                       -> expr
  where
    checkStore e = case lvalue l heap e of
        Just addr -> M.findWithDefault (preserve e) addr store
        Nothing   -> preserve e
    preserve (Expr p n) = case n of
        Field e prop -> Expr p (Field (symEval l heap store e) prop)
        Index e i    -> Expr p (Index (symEval l heap store e) (symEval l heap store i))
        Deref e      -> Expr p (Deref (symEval l heap store e))
        _            -> Expr p n

-- | Core engine for exploring paths and verifying statements symbolically.
-- Returns lists representing distinct execution paths and safety obligations collected.
symExec :: Int -> FuncEnv -> Layout -> Addr -> Heap -> SymStore -> Expr -> [Stmt] 
        -> ([(Expr, Maybe Expr, SymStore)], [(Layout, Addr, SymStore, Expr)], [(Expr, SourcePos, String, Expr, Expr)])
symExec fuel _ _ _ _ _ pc _ | fuel <= 0 = 
    let abortCheck = genExpr (BoolLit False)
        msg = "Analysis aborted: Out of fuel (Path too complex or infinite loop)"
    in ([], [], [(pc, initialPos "<internal>", msg, abortCheck, abortCheck)])
symExec _ _ l nextA _ store pc [] = ([], [(l, nextA, store, pc)], []) 
symExec fuel funcs l nextA heap store pc (Stmt pos stmtNode : stmts) = 
    let f = fuel - 1 in
    case stmtNode of
        Decl _ ty x mExpr -> 
            let valExpr = case mExpr of 
                    Just (Expr _ (Call _ _)) -> genExpr (Var x)
                    Just e                   -> symEval l heap store e
                    Nothing                  -> genExpr (Var x)
                checks = case mExpr of 
                    Just e  -> map (\(p, msg, c) -> (pc, p, msg, c, symEval l heap store c)) (extractSafety l funcs e)
                    Nothing -> []
                sz = sizeOf l ty
                newL = l { lEnv = M.insert x nextA (lEnv l), lTypes = M.insert nextA ty (lTypes l) }
                newStore = M.insert nextA valExpr store
                (r, c, sChecks) = symExec f funcs newL (nextA + sz) heap newStore pc stmts
            in (r, c, checks ++ sChecks)
            
        Assign lhs e@(Expr _ (Call _ _)) -> 
            let evalRhs = lhs
                origChecks = extractSafety l funcs lhs ++ extractSafety l funcs e
                checks = map (\(p, msg, c) -> (pc, p, msg, c, symEval l heap store c)) origChecks
            in case lvalue l heap lhs of
                Just addr -> let (r, c, sChecks) = symExec f funcs l nextA heap (M.insert addr evalRhs store) pc stmts
                             in (r, c, checks ++ sChecks)
                Nothing   -> let (r, c, sChecks) = symExec f funcs l nextA heap store pc stmts
                             in (r, c, checks ++ sChecks)  

        Assign lhs e -> 
            let evalLhs = symEval l heap store lhs
                evalRhs = symEval l heap store e
                origChecks = extractSafety l funcs lhs ++ extractSafety l funcs e
                checks = map (\(p, msg, c) -> (pc, p, msg, c, symEval l heap store c)) origChecks
            in case lhs of
                Expr _ (Index baseArr idxExpr) -> 
                    case lvalue l heap baseArr of
                        Just baseAddr -> 
                            let evalIdx = symEval l heap store idxExpr
                                currentArrState = M.findWithDefault (symEval l heap M.empty baseArr) baseAddr store
                                newArrState = genExpr (ArrayUpdate currentArrState evalIdx evalRhs)
                                newStore = M.insert baseAddr newArrState store
                                (r, c, sChecks) = symExec f funcs l nextA heap newStore pc stmts
                            in (r, c, checks ++ sChecks)
                        Nothing -> 
                            let (r, c, sChecks) = symExec f funcs l nextA heap store pc stmts
                            in (r, c, checks ++ sChecks)
                _ -> case lvalue l heap lhs of
                    Just addr -> let (r, c, sChecks) = symExec f funcs l nextA heap (M.insert addr evalRhs store) pc stmts
                                 in (r, c, checks ++ sChecks)
                    Nothing   -> let (r, c, sChecks) = symExec f funcs l nextA heap store pc stmts
                                 in (r, c, checks ++ sChecks)

        ExprStmt expr -> 
            let origChecks = extractSafety l funcs expr
                checks = map (\(p, msg, c) -> (pc, p, msg, c, symEval l heap store c)) origChecks
                (r, c, sChecks) = symExec f funcs l nextA heap store pc stmts
            in (r, c, checks ++ sChecks)

        Return mExpr -> 
            let evalRet = fmap (symEval l heap store) mExpr
                checks = case mExpr of 
                    Just e  -> map (\(p, msg, c) -> (pc, p, msg, c, symEval l heap store c)) (extractSafety l funcs e)
                    Nothing -> []
            in ([(pc, evalRet, store)], [], checks)
        
        Block innerStmts ->
            let (retI, contI, checksI) = symExec f funcs l nextA heap store pc innerStmts
                restResults = map (\(lI, nI, stI, pI) -> symExec f funcs lI nI heap stI pI stmts) contI
                returns = retI ++ concatMap (\(r,_,_) -> r) restResults
                continues = concatMap (\(_,c,_) -> c) restResults
                checksRest = concatMap (\(_,_,c) -> c) restResults
            in (returns, continues, checksI ++ checksRest)
            
        If cond thn els ->
            let condVal = symEval l heap store cond
                checksC = map (\(p, msg, c) -> (pc, p, msg, c, symEval l heap store c)) (extractSafety l funcs cond)
                
                (retT, contT, checksT) = symExec f funcs l nextA heap store (genExpr (BinOp "&&" pc condVal)) thn
                (retF, contF, checksF) = symExec f funcs l nextA heap store (genExpr (BinOp "&&" pc (genExpr (UnOp "!" condVal)))) (fromMaybe [] els)
                
                mergeStores origStore stT stF = 
                    let keys = nub (M.keys stT ++ M.keys stF)
                        getVal st k = case M.lookup k st of
                            Just v -> v
                            Nothing -> case M.lookup k origStore of
                                Just ov -> ov
                                Nothing -> case reverseLval l k of
                                    (expr:_) -> symEval l heap origStore expr
                                    []       -> genExpr (Var ("_unk_addr_" ++ show k))
                    in M.fromList [ (k, genExpr (Ternary condVal (getVal stT k) (getVal stF k))) | k <- keys ]
                
                mergedCont = case (contT, contF) of
                    ([], []) -> []
                    (ts, []) -> ts
                    ([], fs) -> fs
                    
                    ([(lT, nT, stT, pcT)], [(lF, nF, stF, pcF)]) ->
                        let mergedStore = mergeStores store stT stF
                            mergedPc = genExpr (BinOp "||" pcT pcF)
                            maxNextA = max nT nF
                            mergedLayout = l { lTypes = M.union (lTypes lT) (lTypes lF)
                                             , lEnv   = M.union (lEnv lT) (lEnv lF) }
                        in [(mergedLayout, maxNextA, mergedStore, mergedPc)]
                        
                    (ts, fs) -> ts ++ fs 
                
                restResults = map (\(lI, nI, stI, pI) -> symExec f funcs lI nI heap stI pI stmts) mergedCont
                
                returns = retT ++ retF ++ concatMap (\(r,_,_) -> r) restResults
                continues = concatMap (\(_,c,_) -> c) restResults
                checksRest = concatMap (\(_,_,c) -> c) restResults
            in (returns, continues, checksC ++ checksT ++ checksF ++ checksRest)
            
        While cond Nothing body ->
            let unrollLimit = 5
                unrolledBlock = foldr (\_ acc -> [Stmt pos (If cond (body ++ acc) Nothing)]) [] [1..unrollLimit]

                boundCheckExpr = genExpr (UnOp "!" cond)
                checkStmt = Stmt pos (Decl Dynamic Bool "_bound_check" (Just boundCheckExpr))
                
                (ret, cont, checks) = symExec f funcs l nextA heap store pc (unrolledBlock ++ [checkStmt] ++ stmts)
                
                mapBoundError (p, oldMsg, readable, math)
                    | readable == boundCheckExpr = (p, "Loop unroll limit exceeded. Add invariants.", readable, math)
                    | otherwise = (p, oldMsg, readable, math)
                    
            in (ret, cont, map (\(p_pc, err_pos, msg, r, m) -> 
                    let (_, newMsg, _, _) = mapBoundError (err_pos, msg, r, m)
                    in (p_pc, err_pos, newMsg, r, m)
               ) checks)

        While cond (Just invars) body ->
            let condVal = symEval l heap store cond
                checksC = map (\(p, msg, c) -> (pc, p, msg, c, symEval l heap store c)) (extractSafety l funcs cond)
                (_, dummyConts, _) = symExec 100 funcs l nextA heap M.empty (genExpr (BoolLit True)) body
                mutatedAddrs = nub $ concatMap (\(_, _, st, _) -> M.keys st) dummyConts
                havocStore = foldl (\s a -> M.insert a (genExpr (Var ("_havoc_" ++ show a ++ "_" ++ show nextA))) s) store mutatedAddrs
                invAssumptions = foldl (\acc inv -> genExpr (BinOp "&&" acc (symEval l heap havocStore inv))) (genExpr (BoolLit True)) invars
                exitPc = genExpr (BinOp "&&" invAssumptions (genExpr (UnOp "!" (symEval l heap havocStore condVal))))
                finalPc = genExpr (BinOp "&&" pc exitPc)
                (retS, contS, checksS) = symExec f funcs l nextA heap havocStore finalPc stmts
            in (retS, contS, checksC ++ checksS)
            
        _ -> 
            let (r, c, checks) = symExec f funcs l nextA heap store pc stmts
            in (r, c, checks)


