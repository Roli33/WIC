substituteExpr :: Expr -> Expr -> Expr -> Expr
substituteExpr target replacement inExpr@(Expr pos node) =
    let isMatch = case (node, target) of
            (Var x, Expr _ (Var y)) -> x == y
            _ -> inExpr == target
    in if isMatch then replacement else case node of
        BinOp op e1 e2 -> Expr pos (BinOp op (substituteExpr target replacement e1) (substituteExpr target replacement e2))
        UnOp op e      -> Expr pos (UnOp op (substituteExpr target replacement e))
        Call fname args-> Expr pos (Call fname (map (substituteExpr target replacement) args))
        Index e1 e2    -> Expr pos (Index (substituteExpr target replacement e1) (substituteExpr target replacement e2))
        Field e prop   -> Expr pos (Field (substituteExpr target replacement e) prop)
        AddrOf e       -> Expr pos (AddrOf (substituteExpr target replacement e))
        PreInc e       -> Expr pos (PreInc (substituteExpr target replacement e))
        PostInc e      -> Expr pos (PostInc (substituteExpr target replacement e))
        PreDec e       -> Expr pos (PreDec (substituteExpr target replacement e))
        PostDec e      -> Expr pos (PostDec (substituteExpr target replacement e))
        Ternary c t e  -> Expr pos (Ternary (substituteExpr target replacement c) (substituteExpr target replacement t) (substituteExpr target replacement e))
        Deref e -> case substituteExpr target replacement e of 
                     Expr _ (AddrOf inner) -> inner
                     other -> Expr pos (Deref other)
        _ -> inExpr

substituteMany :: [(Expr, Expr)] -> Expr -> Expr
substituteMany subs inExpr = foldl (\expr (targ, repl) -> substituteExpr targ repl expr) inExpr subs

simplifyBool :: Expr -> Expr
simplifyBool inExpr@(Expr pos node) = case node of
    BinOp "&&" (Expr _ (BoolLit False)) _ -> Expr pos (BoolLit False)
    BinOp "&&" _ (Expr _ (BoolLit False)) -> Expr pos (BoolLit False)
    BinOp "&&" (Expr _ (BoolLit True)) e  -> simplifyBool e
    BinOp "&&" e (Expr _ (BoolLit True))  -> simplifyBool e
    BinOp "||" (Expr _ (BoolLit True)) _  -> Expr pos (BoolLit True)
    BinOp "||" _ (Expr _ (BoolLit True))  -> Expr pos (BoolLit True)
    BinOp "||" (Expr _ (BoolLit False)) e -> simplifyBool e
    BinOp "||" e (Expr _ (BoolLit False)) -> simplifyBool e
    BinOp "&&" e1 e2 -> 
        let e1' = simplifyBool e1; e2' = simplifyBool e2 
        in if e1' == genExpr (BoolLit False) || e2' == genExpr (BoolLit False) then Expr pos (BoolLit False) 
           else if e1' == genExpr (BoolLit True) then e2' 
           else if e2' == genExpr (BoolLit True) then e1' 
           else Expr pos (BinOp "&&" e1' e2')
    BinOp "||" e1 e2 -> 
        let e1' = simplifyBool e1; e2' = simplifyBool e2 
        in if e1' == genExpr (BoolLit True) || e2' == genExpr (BoolLit True) then Expr pos (BoolLit True) 
           else if e1' == genExpr (BoolLit False) then e2' 
           else if e2' == genExpr (BoolLit False) then e1' 
           else Expr pos (BinOp "||" e1' e2')
    UnOp "!" (Expr _ (BinOp ">" a b))  -> Expr pos (BinOp "<=" a b)
    UnOp "!" (Expr _ (BinOp "<" a b))  -> Expr pos (BinOp ">=" a b)
    UnOp "!" (Expr _ (BinOp ">=" a b)) -> Expr pos (BinOp "<" a b)
    UnOp "!" (Expr _ (BinOp "<=" a b)) -> Expr pos (BinOp ">" a b)
    UnOp "!" (Expr _ (BinOp "==" a b)) -> Expr pos (BinOp "!=" a b)
    UnOp "!" (Expr _ (BinOp "!=" a b)) -> Expr pos (BinOp "==" a b)
    UnOp "!" (Expr _ (BoolLit True))   -> Expr pos (BoolLit False)
    UnOp "!" (Expr _ (BoolLit False))  -> Expr pos (BoolLit True)
    _ -> inExpr

-- | Partially evaluates an expression, simplifying nodes where concrete values are known.
partialEval :: Layout -> Heap -> Expr -> Expr
partialEval l heap expr@(Expr pos node) = case node of
    Var _handleCallback -> toLit expr
    Field e p           -> case toLit expr of Expr _ (Field _ _) -> Expr pos (Field (partialEval l heap e) p); lit -> lit
    Index e1 e2         -> case toLit expr of Expr _ (Index _ _) -> Expr pos (Index (partialEval l heap e1) (partialEval l heap e2)); lit -> lit
    Deref e             -> case toLit expr of Expr _ (Deref _)   -> Expr pos (Deref (partialEval l heap e)); lit -> lit
    BinOp op e1 e2 -> 
        let e1' = partialEval l heap e1; e2' = partialEval l heap e2
        in case (e1', e2') of
            (Expr _ (IntLit a), Expr _ (IntLit b)) -> case applyOp op (VInt a) (VInt b) of 
                                                        VInt n -> Expr pos (IntLit n); 
                                                        VBool x -> Expr pos (BoolLit x); 
                                                        _ -> Expr pos (BinOp op e1' e2')
            (Expr _ (BoolLit a), Expr _ (BoolLit b)) -> case applyOp op (VBool a) (VBool b) of 
                                                          VBool x -> Expr pos (BoolLit x); 
                                                          _ -> Expr pos (BinOp op e1' e2')
            (Expr _ (BoolLit True), right) | op == "&&" -> right
            (left, Expr _ (BoolLit True))  | op == "&&" -> left
            (Expr _ (BoolLit False), _)    | op == "&&" -> Expr pos (BoolLit False)
            (_, Expr _ (BoolLit False))    | op == "&&" -> Expr pos (BoolLit False)
            (Expr _ (BoolLit True), _)     | op == "||" -> Expr pos (BoolLit True)
            (_, Expr _ (BoolLit True))     | op == "||" -> Expr pos (BoolLit True)
            (Expr _ (BoolLit False), right)| op == "||" -> right
            (left, Expr _ (BoolLit False)) | op == "||" -> left
            _ -> Expr pos (BinOp op e1' e2')
    UnOp op e -> 
        let e' = partialEval l heap e
        in case e' of 
             Expr _ (IntLit a)  -> case applyUnOp op (VInt a) of VInt n -> Expr pos (IntLit n); _ -> Expr pos (UnOp op e')
             Expr _ (BoolLit a) -> case applyUnOp op (VBool a) of VBool x -> Expr pos (BoolLit x); _ -> Expr pos (UnOp op e')
             _                  -> Expr pos (UnOp op e')
    Call fname args -> Expr pos (Call fname (map (partialEval l heap) args))
    Ternary c t e -> let c' = partialEval l heap c in case c' of 
                       Expr _ (BoolLit True)  -> partialEval l heap t
                       Expr _ (BoolLit False) -> partialEval l heap e
                       _                      -> Expr pos (Ternary c' (partialEval l heap t) (partialEval l heap e))
    _ -> expr
  where
    toLit e = case readLval l heap e of 
                VInt n    -> Expr pos (IntLit n)
                VBool b   -> Expr pos (BoolLit b)
                VDouble d -> Expr pos (DoubleLit d)
                VChar c   -> Expr pos (CharLit c)
                _         -> e

splitAnds :: Expr -> [Expr]
splitAnds (Expr _ (BinOp "&&" e1 e2)) = splitAnds e1 ++ splitAnds e2
splitAnds e = [e]

extractVars :: Expr -> [String]
extractVars (Expr _ node) = case node of
    Var n         -> [n]
    BinOp _ e1 e2 -> extractVars e1 ++ extractVars e2
    UnOp _ e      -> extractVars e
    Ternary c t e -> extractVars c ++ extractVars t ++ extractVars e
    Call _ args   -> concatMap extractVars args
    Index e1 e2   -> extractVars e1 ++ extractVars e2
    Deref e       -> extractVars e
    AddrOf e      -> extractVars e
    Field e _     -> extractVars e
    _             -> []

-- | Extracts implicit safety obligations from an expression (e.g., preventing DivByZero).
extractSafety :: Layout -> t -> Expr -> [(SourcePos, String, Expr)]
extractSafety l funcs (Expr pos node) = case node of
    BinOp "/" e1 e2 -> 
        [(pos, "Division by Zero", genExpr (BinOp "!=" e2 (genExpr (IntLit 0))))] 
        ++ extractSafety l funcs e1 ++ extractSafety l funcs e2
    BinOp "%" e1 e2 -> 
        [(pos, "Modulo by Zero", genExpr (BinOp "!=" e2 (genExpr (IntLit 0))))] 
        ++ extractSafety l funcs e1 ++ extractSafety l funcs e2
    Index arr idx -> 
        let baseChecks = extractSafety l funcs arr ++ extractSafety l funcs idx
            boundsChecks = case typeOf l arr of
                Just (Array _ (Just (Expr _ (IntLit sz)))) -> 
                    [ (pos, "Array Index Out of Bounds", genExpr (BinOp "<" idx (genExpr (IntLit sz))))
                    , (pos, "Array Index Out of Bounds", genExpr (BinOp ">=" idx (genExpr (IntLit 0)))) 
                    ]
                _ -> []
        in boundsChecks ++ baseChecks
    Call _ args             -> concatMap (extractSafety l funcs) args
    ArrayUpdate arr idx val -> extractSafety l funcs arr ++ extractSafety l funcs idx ++ extractSafety l funcs val
    BinOp _ e1 e2           -> extractSafety l funcs e1 ++ extractSafety l funcs e2
    UnOp _ e                -> extractSafety l funcs e
    Ternary c t e           -> extractSafety l funcs c ++ extractSafety l funcs t ++ extractSafety l funcs e
    _                       -> []


