{-|
Module      : Analyzer
Description : Static analysis engine using Symbolic Execution and Z3.

This module is responsible for analyzing the AST generated by the Parser.
It uses a hybrid approach: concrete evaluation where possible, and symbolic
execution to explore different program paths. It translates program states 
and compile-time contracts (invariants, pre/postconditions) into SMT queries
to mathematically prove the absence of safety violations (like division by zero, 
array out-of-bounds) and contract breaches.
-}

