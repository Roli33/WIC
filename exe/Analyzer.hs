applyOp :: String -> Value -> Value -> Value
applyOp "+" (VInt a) (VInt b)       = VInt (a + b)
applyOp "+" (VDouble a) (VDouble b) = VDouble (a + b)
applyOp "+" (VInt a) (VDouble b)    = VDouble (fromIntegral a + b)
applyOp "+" (VDouble a) (VInt b)    = VDouble (a + fromIntegral b)
applyOp "+" (VAddr a) (VInt b)      = VAddr (a + fromIntegral b)
applyOp "+" (VInt a) (VAddr b)      = VAddr (fromIntegral a + b)
applyOp "-" (VInt a) (VInt b)       = VInt (a - b)
applyOp "-" (VDouble a) (VDouble b) = VDouble (a - b)
applyOp "-" (VInt a) (VDouble b)    = VDouble (fromIntegral a - b)
applyOp "-" (VDouble a) (VInt b)    = VDouble (a - fromIntegral b)
applyOp "-" (VAddr a) (VInt b)      = VAddr (a - fromIntegral b)
applyOp "-" (VAddr a) (VAddr b)     = VInt (fromIntegral (a - b))
applyOp "*" (VInt a) (VInt b)       = VInt (a * b)
applyOp "*" (VDouble a) (VDouble b) = VDouble (a * b)
applyOp "*" (VInt a) (VDouble b)    = VDouble (fromIntegral a * b)
applyOp "*" (VDouble a) (VInt b)    = VDouble (a * fromIntegral b)
applyOp "/" (VInt a) (VInt b)       | b /= 0 = VInt (a `div` b)
applyOp "/" (VDouble a) (VDouble b) | b /= 0.0 = VDouble (a / b)
applyOp ">" (VInt a) (VInt b)       = VBool (a > b)
applyOp ">" (VDouble a) (VDouble b) = VBool (a > b)
applyOp "<" (VInt a) (VInt b)       = VBool (a < b)
applyOp "<" (VDouble a) (VDouble b) = VBool (a < b)
applyOp ">=" (VInt a) (VInt b)      = VBool (a >= b)
applyOp ">=" (VDouble a) (VDouble b)= VBool (a >= b)
applyOp "<=" (VInt a) (VInt b)      = VBool (a <= b)
applyOp "<=" (VDouble a) (VDouble b)= VBool (a <= b)
applyOp "==" (VInt a) (VInt b)      = VBool (a == b)
applyOp "==" (VDouble a) (VDouble b)= VBool (a == b)
applyOp "==" (VChar a) (VChar b)    = VBool (a == b)
applyOp "==" (VBool a) (VBool b)    = VBool (a == b)
applyOp "==" (VAddr a) (VAddr b)    = VBool (a == b) 
applyOp "!=" a b                    = case applyOp "==" a b of VBool res -> VBool (not res); _ -> VUnknown
applyOp "&&" (VBool a) (VBool b)    = VBool (a && b)
applyOp "||" (VBool a) (VBool b)    = VBool (a || b)
applyOp _ _ _                       = VUnknown

applyUnOp :: String -> Value -> Value
applyUnOp "-" (VInt a)    = VInt (-a)
applyUnOp "-" (VDouble a) = VDouble (-a)
applyUnOp "!" (VBool b)   = VBool (not b)
applyUnOp _ _             = VUnknown

-- | Evaluates an expression concretely where possible, returning VUnknown if symbolic.
evalPure :: Layout -> Heap -> Expr -> Value
evalPure l heap expr@(Expr _ node) = case node of
    IntLit n      -> VInt n
    DoubleLit d   -> VDouble d
    CharLit c     -> VChar c
    BoolLit b     -> VBool b
    AddrOf e      -> case lvalue l heap e of Just addr -> VAddr addr; Nothing -> VUnknown
    Var _         -> readLval l heap expr
    Field _ _     -> readLval l heap expr
    Index _ _     -> readLval l heap expr
    Deref _       -> readLval l heap expr
    BinOp op e1 e2-> applyOp op (evalPure l heap e1) (evalPure l heap e2)
    UnOp op e     -> applyUnOp op (evalPure l heap e)
    Ternary c t e -> case evalPure l heap c of 
                       VBool True  -> evalPure l heap t
                       VBool False -> evalPure l heap e
                       _           -> VUnknown
    _             -> VUnknown

readLval :: Layout -> Heap -> Expr -> Value
readLval l heap e = case lvalue l heap e of
    Just addr -> M.findWithDefault VUnknown addr heap
    Nothing   -> VUnknown


