alloc :: String -> Type -> Value -> Analyzer Addr
alloc name ty val = do
    l <- getLayout
    addr <- gets nextAddr
    let sz = sizeOf l ty
    modify (\s -> s { nextAddr = addr + sz
                    , env = M.insert name addr (env s)
                    , heap = M.insert addr val (heap s)
                    , heapTypes = M.insert addr ty (heapTypes s) })
    return addr

getFootprint :: Layout -> Heap -> [Value] -> [Addr]
getFootprint l heap initialVals = 
    let startAddrs = [ a | VAddr a <- initialVals ]
        expandSize addr = case M.lookup addr (lTypes l) of Just ty -> [addr .. addr + sizeOf l ty - 1]; Nothing -> [addr]
        findReachable [] visited = visited
        findReachable (a:worklist) visited 
            | a `elem` visited = findReachable worklist visited
            | otherwise = 
                let block = expandSize a
                    vals = map (\addr -> M.findWithDefault VUnknown addr heap) block
                    newAddrs = [ ptr | VAddr ptr <- vals, ptr `notElem` visited ]
                in findReachable (newAddrs ++ worklist) (block ++ visited)
    in nub $ findReachable startAddrs []

buildSummaries :: Analyzer ()
buildSummaries = do
    funcMap <- gets funcs
    forM_ (M.toList funcMap) $ \(fname, funcDef) -> do
        let isAxiom = isJust (funcPostconds funcDef) && isJust (funcInvars funcDef)
        
        if isAxiom then
            modify (\s -> s { summaries = M.insert fname (FuncSummary [] []) (summaries s) })
        else do
            l <- getLayout
            let paramNames = map (\(Arg _ n) -> n) (funcArgs funcDef)
            let paramTypes = map (\(Arg t _) -> t) (funcArgs funcDef)
            
            let startAddr = 1000 
            let localEnv = M.fromList (zip paramNames [startAddr..])
            let localTypes = M.fromList (zip [startAddr..] paramTypes)
            
            let targetStartAddr = startAddr + length paramNames
            let (dummyHeap, dummyTypes, ptrMap) = foldl (\(h, ts, m) (name, ty, addr) -> 
                    case ty of
                        Ptr innerTy -> 
                            let tAddr = targetStartAddr + addr
                            in (M.insert addr (VAddr tAddr) h, M.insert tAddr innerTy ts, M.insert tAddr (name, innerTy) m)
                        _ -> (h, ts, m)
                  ) (M.empty, localTypes, M.empty) (zip3 paramNames paramTypes [startAddr..])

            let sandboxLayout = l { lEnv = localEnv, lTypes = dummyTypes }
            
            let maxAddr = targetStartAddr + length paramNames + 1000
            let (returns, continues, _) = symExec 1000 funcMap sandboxLayout maxAddr dummyHeap M.empty (genExpr (BoolLit True)) (funcBody funcDef)
            
            let allPaths = returns ++ map (\(_, _, st, pc) -> (pc, Nothing, st)) continues
            
            let pathExprs = mapMaybe (\(pc, mRet, store) ->
                    let retFact = case mRet of
                            Just retExpr -> [genExpr (BinOp "==" (genExpr (Var "res")) retExpr)]
                            Nothing -> []
                        ptrFacts = mapMaybe (\(targetAddr, (pName, _)) -> 
                                case M.lookup targetAddr store of
                                    Just newVal -> Just (genExpr (BinOp "==" (genExpr (Deref (genExpr (Var pName)))) newVal))
                                    Nothing -> Nothing
                            ) (M.toList ptrMap)
                        allFacts = retFact ++ ptrFacts
                    in if null allFacts then Nothing 
                       else Just (if pc == genExpr (BoolLit True) 
                                  then foldl1 (\acc f -> genExpr (BinOp "&&" acc f)) allFacts 
                                  else genExpr (BinOp "&&" pc (foldl1 (\acc f -> genExpr (BinOp "&&" acc f)) allFacts)))
                  ) allPaths
                  
            let computedPosts = if null pathExprs then [] else [foldl1 (\acc e -> genExpr (BinOp "||" acc e)) pathExprs]
            
            let mutatedAddrs = nub (concatMap (\(_, _, st) -> M.keys st) allPaths)
            let mutatedVars = [ pName | targetAddr <- mutatedAddrs, Just (pName, _) <- [M.lookup targetAddr ptrMap] ]
            
            modify (\s -> s { summaries = M.insert fname (FuncSummary mutatedVars computedPosts) (summaries s) })

registerCallFacts :: Maybe Expr -> String -> [Expr] -> Analyzer ()
registerCallFacts mAssignedVar fname argExprs = do
    callerLayout <- getLayout
    callerHeap <- gets heap
    funcMap <- gets funcs
    sumMap <- gets summaries
    
    case M.lookup fname funcMap of
        Just funcDef -> do
            let paramNames = map (\(Arg _ n) -> n) (funcArgs funcDef)
            let subs = zip (map (genExpr . Var) paramNames) argExprs
            
            let summary = M.findWithDefault (FuncSummary [] []) fname sumMap
            let explicitPost = fromMaybe [] (funcPostconds funcDef)

            let mutatedArgs = [ argExprs !! i | (i, name) <- zip [0..] paramNames, name `elem` modifiedParams summary ]
            argVals <- mapM evalExpr mutatedArgs
            let footprint = getFootprint callerLayout callerHeap argVals
            
            let mutatedCallerVars = [ name | (name, baseAddr) <- M.toList (lEnv callerLayout), Just ty <- [M.lookup baseAddr (lTypes callerLayout)], let sz = sizeOf callerLayout ty, any (\addr -> addr >= baseAddr && addr < baseAddr + sz) footprint ]
            
            modify (\s -> s { heap = foldr M.delete (heap s) footprint })
            modify (\s -> s { facts = filter (\f -> not (any (`elem` mutatedCallerVars) (extractVars f))) (facts s) })

            updatedHeap <- gets heap 

            let allPosts = explicitPost ++ implicitPosts summary
            let callerStandard = map (substituteMany subs) (concatMap splitAnds allPosts)
            
            let finalFacts = case mAssignedVar of 
                    Just varExpr -> map (substituteExpr (genExpr (Var "res")) varExpr) callerStandard
                    Nothing -> callerStandard

            let evaluatedFinalFacts = map (partialEval callerLayout updatedHeap) finalFacts

            modify (\s -> s { facts = facts s ++ evaluatedFinalFacts })
            
        Nothing -> do
            argVals <- mapM evalExpr argExprs
            let footprint = getFootprint callerLayout callerHeap argVals
            let mutatedCallerVars = [ name | (name, baseAddr) <- M.toList (lEnv callerLayout), Just ty <- [M.lookup baseAddr (lTypes callerLayout)], let sz = sizeOf callerLayout ty, any (\addr -> addr >= baseAddr && addr < baseAddr + sz) footprint ]
            
            modify (\s -> s { facts = filter (\f -> not (any (`elem` mutatedCallerVars) (extractVars f))) (facts s) })
            modify (\s -> s { heap = foldr M.delete (heap s) footprint })
            return ()

